def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

def floor_divide(a, b):
    return a // b

def modulus(a, b):
    return a % b

def power(a, b):
    return a ** b


print("Addition 5 + 3:", add(5, 3))
print("Subtraction 5 - 3:", subtract(5, 3))
print("Multiplication 5 * 3:", multiply(5, 3))
print("Division 5 / 3:", divide(5, 3))
print("Floor Division 5 // 3:", floor_divide(5, 3))
print("Modulus 5 % 3:", modulus(5, 3))
print("Power 5 ** 3:", power(5, 3))